# ---- 海选提示词：每个区块独立发一次 ----
# {live_type} 直播类型；{weights} 该类型的评分侧重；{max_candidates} 候选上限；{chunk_text} 区块原文
_SCREENING_TEMPLATE = """你正在审看一场「{live_type}」直播的一段录像（下面是带时间戳的文字稿）。

你不是总结助手。你是直播短视频运营，这一轮只需要回答一个问题：
这段录像里，有没有可能值得剪成短视频发布的片段？

【最重要的原则：宁多勿少】
- 拿不准的候选，给。让后面的复审去淘汰，不要在海选阶段就下杀手。
- 每段至少挑出 1 个最有潜力的候选；只有整段从头到尾确实毫无可剪点，才允许返回空列表。
- 「不够完美」不是不给候选的理由；「完全没有可看性」才是。

判断视角（v0.3.2 评分体系 v3，本场侧重：{weights}）：
每个候选都自问一句——一个不认识主播的新用户刷到开头几秒，为什么会停下来？
用这五个维度去发现候选（海选只做粗略直觉判断，打分会留给复审）：
1. 三秒吸引力：标题 + 开头 3 秒有没有钩子（误会 / 悬念 / 强反差 / 离谱事件）
2. 反差 / 意外：以为 A 结果 B、高期待低结果、身份反差、认知冲突（误会 > 反转 > 普通事件）
3. 人物表现力：主播的独特反应、经典表达、夸张情绪，能不能形成主播标签
4. 独立成片：剪出来不需要大量直播背景，陌生观众能否理解
5. 事件完整度：有没有 开始 → 过程 → 结果 的结构

同时警惕「假高光」——以下情况只是表面热闹，通常不是真爆点（复审会过滤，但你在海选时别把它们当第一选择）：
- 普通失误（东西掉了、洒了、小操作失败）
- 普通展示（开包装、展示商品、普通介绍）
- 单纯惊讶（「哇好少」——没有反差、故事、冲突的惊讶）
- 普通评价（「不好吃」「一般」）
除非它们伴随巨大反差或主播反应极强，才值得给候选。

候选分三种类型，各有各的判断标准：
1. 事件型——有明确事件、冲突、信息价值、完整逻辑（适合知识/访谈/分析）
2. 情绪型——直播的核心类型：情绪爆发、震惊反应、生气、感动、争议回应
3. 梗型——直播非常重要的类型：一句话成为梗、逆天发言、搞笑反应

其他要求：
- 时间必须用文字稿里出现过的原始时间戳；相邻台词可以合并成一个片段。
- 文字稿由语音识别生成，可能有错字，按语义容错理解。

只输出一个 JSON 对象，格式如下（本段 1~{max_candidates} 个候选）：
{{
  "candidates": [
    {{
      "start_time": "片段开始时间",
      "end_time": "片段结束时间",
      "title": "适合发短视频的标题，20字以内",
      "highlight_type": "事件型/情绪型/梗型 之一",
      "score": 8,
      "reason": "为什么值得剪：必须回答『陌生观众为什么会停留』，40字以内",
      "category": "冲突/反转/金句/情绪/操作/观点/其他 之一",
      "viral_probability": "高/中/低",
      "editing_advice": "剪辑建议，含开头3秒怎么设计，40字以内",
      "confidence": 0.8
    }}
  ]
}}
确实没有任何可剪点才输出 {{"candidates": []}}。

文字稿：
{chunk_text}"""

# 漏检重扫时的追加提示（质检怀疑该区块有漏网之鱼）
_RETRY_HINT = """
【特别提示】质检环节怀疑这一段存在被漏掉的爆点，请用更宽的标准重新审视这一段。
重点找：情绪型（情绪变化、语气突变）和梗型（可做标题的逆天发言）片段。
"""


def build_screening_prompt(chunk_text: str, live_type: str, max_candidates: int,
                           weights: str = "", second_pass: bool = False) -> str:
    """拼海选需求单（一个区块一份）。

    chunk_text     —— chunker 吐出来的区块带时间戳文本
    live_type      —— 直播类型（提示词里告诉 AI 这是什么场）
    max_candidates —— 该区块最多几个候选（Token 降级时会压到 1）
    weights        —— 该类型的评分侧重（config.LIVE_TYPE_WEIGHTS）
    second_pass    —— 质检漏检后的重扫（True 时加更宽标准的提示）
    """
    prompt = _SCREENING_TEMPLATE.format(
        live_type=live_type,
        weights=weights or "各维度均衡",
        max_candidates=max_candidates,
        chunk_text=chunk_text,
    )
    if second_pass:
        prompt = _RETRY_HINT + prompt
    return prompt


# ---- 漏检质检提示词：候选列表 + 区块摘要 → 哪些区块可能漏了爆点 ----
_MISS_CHECK_TEMPLATE = """你是直播内容质检员。海选刚刚完成了对一场「{live_type}」直播的分段扫描，
你的任务是检查一件事：有没有区块明显存在爆点，却没有产出任何候选（或候选明显偏弱）？

你不是在找高光，你是在找「海选的漏检」。

判断线索：
- 摘要里的强信号句（情绪词、冲突词密集）但该区块候选很少或没有 → 可疑
- 摘要显示情绪变化、语气突变、话题转折，但候选池没覆盖 → 可疑
- 普通闲聊区块没有候选 → 正常，不要报

只把你认为真的可疑的区块报出来；都不可疑就输出空列表。

只输出一个 JSON 对象，格式如下：
{{
  "checks": [
    {{
      "chunk": 3,
      "miss_risk": true,
      "reason": "该区域存在明显情绪变化，但未进入候选池"
    }}
  ]
}}

【各区块摘要】
{summaries_text}

【已进入候选池的片段】
{candidates_text}"""


def build_miss_check_prompt(live_type: str, summaries_text: str,
                            candidates_text: str) -> str:
    """拼漏检质检需求单（区块摘要 + 候选简表，一次调用查完）。"""
    return _MISS_CHECK_TEMPLATE.format(
        live_type=live_type,
        summaries_text=summaries_text,
        candidates_text=candidates_text,
    )


# ---- 复审提示词：全部候选一次审完，五维打分 + 正反理由 + 分析报告 ----
# {candidates_text} 编排器拼好的候选清单（含海选理由 + 原文节选）
#
# v0.3.2 评分体系 v3：
#   AI 只输出五个维度的子分（1-10），不输出 final_score / grade——
#   本地按 config.SCORE_V3_WEIGHTS 加权算总分、按阈值定级。
#   这样定级可解释、可审计，也杜绝 AI「先给个理由、再顺手打个高分」。
_REVIEW_TEMPLATE = """你是一名资深直播短视频运营，现在进入终审环节。

海选已经捞出了一批候选片段。你的任务不是找更多，而是逐条审判：
「剪出来发出去，有没有人看？」——一个不认识主播、偶然刷到的新用户，为什么会停下来？

【最重要的视角转变】
你不是在总结这场直播发生了什么，你是在判断什么值得剪。
「主播有情绪波动」不等于「值得剪」。真正的问题是：
- 标题和开头 3 秒，能不能让陌生人停下来？
- 这段有没有传播结构（误会 / 反差 / 反转 / 记忆点），而不只是「有事发生」？

【五维评分】对每个候选，只输出以下五个子分（每个 1-10 整数，独立判断）：
1. hook_score（三秒吸引力，权重最高）：
   标题 + 开头 3 秒的钩子强度。陌生人看到第一眼会不会想看下去？
   高分例：「主播以为黄腐鸡是咖啡，喝之前完全不知道」
   低分例：「主播不小心洒了一杯饮料」「主播普通评价一个商品」
2. contrast_score（反差/意外）：
   以为 A 结果 B、高期待→低结果、身份反差、认知冲突。
   优先级：误会 > 反转 > 普通事件。
   高分例：把黄腐鸡误认为咖啡并喝下去。
   低分例：饮料粉洒出来（只是失误，没有认知落差）。
3. persona_score（人物表现力）：
   主播自身的独特反应、经典表达、夸张情绪、可形成主播标签的瞬间。
   注意：不是「主播说了一句话」，而是这句话/反应有没有个人辨识度。
4. standalone_score（独立成片）：
   剪出来以后，不依赖大量直播背景，陌生观众能不能看懂？
   需要大量前因后果的片段 → 打低分。
5. completeness_score（事件完整度）：
   有没有「开始（发生什么）→ 过程（冲突发展）→ 结果（反应/结论）」的完整结构？
   只有半截情绪、没头没尾 → 打低分。

【不值得剪的负面清单】对每个候选，判断是否命中以下规则，命中就填进 negative_flags：
1. 普通失误：东西掉了、洒了、操作失败、小错误——除非产生巨大反差或主播反应极强
2. 普通展示：打开包装、展示商品、普通介绍
3. 单纯惊讶：惊讶 ≠ 高光。「哇，好少」如果没有反差、故事、冲突，就要触发本规则
4. 依赖上下文：陌生用户不知道前因后果就无法理解的片段
5. 普通评价：「不好吃」「一般」「还行」——除非形成特殊比喻或经典梗
命中的候选会被系统自动封顶（最高 B 级，进不了 A/S），所以请诚实判断，不要手软。

【案例对照——帮助你校准判断】

值得剪的高价值案例：
- 案例 A：主播误把「黄腐鸡」当咖啡，喝之前完全不知道。→ 误会 + 反差 + 结果明显，钩子天然成立。
- 案例 B：主播评价军粮「像纸盒子」。→ 具体形容、有画面感，一句话就能当标题，容易传播。
- 案例 C：主播评价罐头「像指甲盖」。→ 独特表达，用户容易记住，是天然的记忆点。

不值得剪的低价值案例（别给高分）：
- 案例 D：主播饮料粉冲泡时洒了出来。→ 只有「事故」，没有传播结构，陌生人没有停留理由。
- 案例 E：打开包装发现东西少，说「哇好少」。→ 单纯惊讶，没有强反差（除非有「以为很多结果很少」的期待落差做铺垫）。

【每个候选必答的两个问题】
1. why_cut（为什么值得剪，50 字内）：必须包含——陌生观众为什么停留？核心传播点是什么？
   如果有传播点写不出来，说明它可能不值得剪。
2. risk（最大风险 / 可能不值得剪的地方，40 字内）：必须诚实指出这个候选的短板。
   例如：需要前因后果、画面冲击依赖剪辑、主播反应不够强、题材太小众。不许写「无」。

【分级参考（系统会按五维子分加权定级，你不用输出等级）】
- S 级爆款候选：三秒吸引力高 + 有传播结构 + 有明显记忆点
- A 级强推荐：适合制作正式切片
- B 级测试素材：有潜力，但需要人工判断
- C 级备用素材：有内容，但传播能力弱
- 命中负面清单的，最高只能到 B 级

同时，给整场直播写一份分析报告。用户需要你解释清楚：为什么没有推荐更多片段——
不解释，用户会以为你没认真分析。

只输出一个 JSON 对象，格式如下：
{{
  "results": [
    {{
      "title": "对应候选的标题，原样返回",
      "hook_score": 8,
      "contrast_score": 6,
      "persona_score": 7,
      "standalone_score": 5,
      "completeness_score": 6,
      "negative_flags": ["普通失误"],
      "why_cut": "陌生观众为什么停留 + 核心传播点，50字内",
      "risk": "最大风险或短板，40字内",
      "confidence": 0.7
    }}
  ],
  "report": {{
    "summary": "本场直播主要内容，60字以内",
    "best_spread_point": "本场最强传播点是什么、为什么，40字以内",
    "overall": "对整场内容的整体评价，40字以内",
    "why_not_more": "为什么没有推荐更多片段，向用户解释清楚，60字以内"
  }}
}}
results 的条目数必须和候选数一致，顺序一一对应。
negative_flags 没有命中就填 []，命中几个填几个（只能从上面 5 条规则里选）。

候选清单：
{candidates_text}"""


def build_review_prompt(candidates_text: str) -> str:
    """拼复审需求单（所有候选 + 原文节选，一次调用审完）。"""
    return _REVIEW_TEMPLATE.format(candidates_text=candidates_text)
